/** char → 7 行字符串数组 */
export const GLYPHS = (function build() {
  const map = new Map();
  for (const [ch, raw] of Object.entries(RAW)) {
    const rows = raw.split('/');
    if (rows.length !== GLYPH_H) throw new Error('字形 ' + ch + ' 行数不是 ' + GLYPH_H);
    for (const r of rows) {
      if (r.length !== GLYPH_W) throw new Error('字形 ' + ch + ' 有不是 ' + GLYPH_W + ' 宽的列: "' + r + '"');
    }
    map.set(ch, rows);
  }
  return map;
})();

export function glyphOf(ch) {
  const up = String(ch).toUpperCase();
  if (GLYPHS.has(up)) return GLYPHS.get(up);
  if (GLYPHS.has(ch)) return GLYPHS.get(ch);
  return GLYPHS.get('?');
}

export function measureText(text, options = {}) {
  const scale = Math.max(1, options.scale | 0 || 1);
  const spacing = options.spacing == null ? 1 : options.spacing;
  const chars = [...String(text)];
  if (!chars.length) return { width: 0, height: 0 };
  return {
    width: chars.length * (GLYPH_W + spacing) * scale - spacing * scale,
    height: GLYPH_H * scale,
  };
}

export default { GLYPHS, GLYPH_W, GLYPH_H, glyphOf, measureText };
